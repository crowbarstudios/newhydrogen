            <h2 class="asia-market-title" id="asia-market-title">Asia: Where Hydrogen Demand Meets <strong>Scarce Supply</strong></h2>
            <p>Four of Asia’s largest economies already account for a large share of the world’s hydrogen and ammonia use. Here is who uses it, how they get it today, and what they need next.</p>
        </header>

